    signal clk         : std_logic := '0';
    signal rst_n       : std_logic := '0';
    signal data_in     : std_logic_vector(31 downto 0) := (others => '0');
    signal data_out    : std_logic_vector(31 downto 0);
    signal ack_in      : std_logic := '0';
    signal input_ready : std_logic;
    signal ready       : std_logic := '0';
    signal valid       : std_logic;
    signal start_out   : std_logic;

begin
    clk <= not clk after C_CLK_PERIOD / 2;

    dut : entity work.hawk_verify(rtl)
        port map (
            clk         => clk,
            rst_n       => rst_n,
            data_in     => data_in,
            data_out    => data_out,
            ack_in      => ack_in,
            input_ready => input_ready,
            ready       => ready,
            valid       => valid,
            start_out   => start_out
        );

    -- Comprobaciones del protocolo en los flancos de transferencia.
    protocol_monitor : process(clk)
        variable pending_start : boolean := false;
        variable stalled       : boolean := false;
        variable held_data     : std_logic_vector(31 downto 0);
    begin
        if rising_edge(clk) then
            if rst_n = '0' then
                pending_start := false;
                stalled := false;
            else
                assert not is_x(input_ready) and not is_x(valid) and not is_x(start_out)
                    report "Control desconocido" severity failure;
                if stalled then
                    assert valid = '1' and data_out = held_data
                        report "Resultado modificado mientras ready=0" severity failure;
                end if;
                if start_out = '1' then
                    assert not pending_start and valid = '0'
                        report "start_out duplicado o simultaneo con valid" severity failure;
                    pending_start := true;
                end if;
                if valid = '1' then
                    assert pending_start and input_ready = '0'
                        report "Salida sin start_out o entrada habilitada durante salida" severity failure;
                    assert not is_x(data_out) and unsigned(data_out) <= 1
                        report "La salida debe ser una palabra 0 o 1" severity failure;
                    if ready = '1' then
                        pending_start := false;
                    end if;
                end if;
                stalled := valid = '1' and ready = '0';
                held_data := data_out;
            end if;
        end if;
    end process protocol_monitor;

    stimulus : process
        procedure wait_input is
            variable cycles : natural := 0;
        begin
            while input_ready /= '1' loop
                wait until falling_edge(clk);
                cycles := cycles + 1;
                assert cycles < 64
                    report "Timeout de reset/recuperacion interna" severity failure;
                assert valid = '0' and start_out = '0'
                    report "Salida espuria durante limpieza" severity failure;
            end loop;
        end procedure;

        procedure reset_dut is
        begin
            wait until falling_edge(clk);
            rst_n <= '0'; ack_in <= '0'; ready <= '0';
            for cycle in 1 to 8 loop
                wait until rising_edge(clk); wait for 1 ns;
                assert valid = '0' and start_out = '0' and input_ready = '0'
                    report "Interfaz activa durante reset externo" severity failure;
            end loop;
            wait until falling_edge(clk); rst_n <= '1';
            wait until falling_edge(clk);
            wait_input;
        end procedure;

        procedure send_word(value : std_logic_vector(31 downto 0)) is
        begin
            assert input_ready = '1'
                report "El DUT dejo de aceptar datos durante la carga" severity failure;
            ack_in <= '1'; data_in <= value;
            wait until rising_edge(clk);
            assert valid = '0' and start_out = '0'
                report "Resultado prematuro durante carga" severity failure;
            wait until falling_edge(clk);
        end procedure;

        procedure load_case(index : natural) is
            variable word : std_logic_vector(31 downto 0);
        begin
            wait_input;
            for i in 0 to 15 loop
                send_word(C_H0(index)((i+1)*32-1 downto i*32));
            end loop;
            for polynomial in 0 to 2 loop
                for i in 0 to 511 loop
                    -- Datos estables durante pausas, nunca se inyectan X.
                    if index mod 2 = 0 and i mod 17 = 0 then
                        ack_in <= '0';
                        wait until falling_edge(clk);
                        assert input_ready = '1' and valid = '0'
                            report "Pausa de entrada altera el protocolo" severity failure;
                    end if;
                    case polynomial is
                        when 0 => word := std_logic_vector(to_signed(C_Q00(index)(i), 32));
                        when 1 => word := std_logic_vector(to_signed(C_Q01(index)(i), 32));
                        when others => word := std_logic_vector(to_signed(C_W1(index)(i), 32));
                    end case;
                    send_word(word);
                end loop;
            end loop;
            ack_in <= '0';
            assert input_ready = '0' report "Entrada habilitada al terminar la carga" severity failure;
        end procedure;

        procedure finish_case(index : natural) is
            variable completed : boolean := false;
            variable starts    : natural := 0;
            variable cleanup   : natural := 0;
        begin
            -- Alterna receptor listo de antemano y backpressure prolongado.
            if index mod 2 = 1 then ready <= '1'; else ready <= '0'; end if;
            for cycle in 0 to C_TIMEOUT loop
                if start_out = '1' then starts := starts + 1; end if;
                if valid = '1' then completed := true; exit; end if;
                assert input_ready = '0' report "Entrada habilitada durante calculo" severity failure;
                wait until falling_edge(clk);
            end loop;
            assert completed report "Timeout: " & case_name(index) severity failure;
            assert starts = 1 report "Numero incorrecto de start_out" severity failure;
            assert data_out(0) = C_ERROR(index) and unsigned(data_out(31 downto 1)) = 0
                report "Resultado incorrecto: " & case_name(index) &
                       "; esperado error=" & std_logic'image(C_ERROR(index)) &
                       "; obtenido=" & std_logic'image(data_out(0)) severity failure;
            if index mod 2 = 0 then
                for cycle in 1 to 7 loop
                    wait until falling_edge(clk);
                    assert valid = '1' and data_out(0) = C_ERROR(index)
                        report "No conserva el resultado bajo backpressure" severity failure;
                end loop;
            end if;
            ready <= '1';
            wait until falling_edge(clk);
            ready <= '0';
            assert valid = '0' and input_ready = '0'
                report "No comienza la limpieza tras aceptar el resultado" severity failure;
            -- Ofrece basura mientras input_ready=0: no debe contaminar la
            -- siguiente operacion. Se retira antes de la primera aceptacion.
            ack_in <= '1'; data_in <= x"DEADBEEF";
            while input_ready /= '1' loop
                wait until falling_edge(clk);
                cleanup := cleanup + 1;
                assert cleanup < 64 and valid = '0' and start_out = '0'
                    report "Limpieza bloqueada o resultado repetido" severity failure;
            end loop;
            ack_in <= '0';
            for cycle in 1 to 3 loop
                wait until falling_edge(clk);
                assert input_ready = '1' and valid = '0'
                    report "Actividad espuria despues de la operacion" severity failure;
            end loop;
            report "Caso " & integer'image(index) & " OK: " & case_name(index);
        end procedure;
    begin
        reset_dut;
        -- Aborta una carga parcial: elimina h0 y parte de q00 pendientes.
        for i in 0 to 39 loop send_word(std_logic_vector(to_unsigned(i+1, 32))); end loop;
        reset_dut;

        -- Aborta primero RebuildS0 y despues PolyQnorm, sin esperar resultado.
        load_case(0);
        for i in 1 to 10000 loop
            wait until falling_edge(clk);
            assert valid = '0' report "Fin prematuro antes del reset de RebuildS0" severity failure;
        end loop;
        reset_dut;
        load_case(0);
        for i in 1 to 60000 loop
            wait until falling_edge(clk);
            assert valid = '0' report "Fin prematuro antes del reset de PolyQnorm" severity failure;
        end loop;
        reset_dut;

        -- Todos los casos siguientes se encadenan sin reset externo.
        for test in 0 to C_CASES - 1 loop
            load_case(test);
            finish_case(test);
        end loop;
        report "PASS: HawkVerify, todos los casos y resets superados";
        -- stop;
        wait;
    end process stimulus;
end architecture simulation;
