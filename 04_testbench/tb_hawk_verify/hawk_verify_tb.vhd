    constant C_ERROR : std_logic_vector(0 to C_CASES - 1) := "0101111001010";
    function case_name(index : natural) return string is
    begin
        case index is
            when 0 => return "Impulso valido";
            when 1 => return "Rechazo temprano: q00 negativo";
            when 2 => return "Recuperacion: primer w1 no nulo en indice 511";
            when 3 => return "Sym-break: w1 completamente cero";
            when 4 => return "Sym-break: negativo antes de positivo";
            when 5 => return "Residuos P1 y P2 diferentes";
            when 6 => return "Residuos iguales pero no divisibles por n";
            when 7 => return "Norma 8316: limite 8317";
            when 8 => return "Norma 8317: limite 8317";
            when 9 => return "Norma 8318: limite 8317";
            when 10 => return "Recuperacion: w1 denso con signos y h0 no uniforme";
            when 11 => return "q00 no constante y q01 denso: oraculo completo";
            when 12 => return "Recuperacion final tras caso complejo";
            when others => return "Caso desconocido";
        end case;
    end function;
